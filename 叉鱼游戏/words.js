let selectedGrade = localStorage.getItem('selectedGrade') || '1-3';
if (!gradePaths[selectedGrade]) {
    selectedGrade = '1-3';
}

let currentAudioPath = gradePaths[selectedGrade] || 'assets/audio';

function getAudioPath() {
    return currentAudioPath;
}

function getCurrentWords() {
    return gradeWordLists[selectedGrade] || gradeWordLists['1-3'] || [];
}

function getSelectedGrade() {
    return selectedGrade;
}

function selectGrade(grade) {
    if (gradePaths[grade]) {
        selectedGrade = grade;
        currentAudioPath = gradePaths[grade];
        localStorage.setItem('selectedGrade', grade);
        if (typeof window !== 'undefined') {
            window.selectedGrade = selectedGrade;
            window.currentAudioPath = currentAudioPath;
        }
        console.log('Switched to grade:', gradeNames[grade]);
        return true;
    }
    return false;
}

