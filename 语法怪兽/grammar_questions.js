  get all() { return Object.values(GRAMMAR_QUESTIONS).flatMap((terms) => Object.values(terms).flat()); },
  forGrade(grade) {
    const terms = GRAMMAR_QUESTIONS[String(grade)] || {};
    return Object.values(terms).flat();
  },
  forBook(grade, term) { return GRAMMAR_QUESTIONS[String(grade)]?.[term] || []; },
  random(grade, term, count = 1) {
    const pool = [...this.forBook(grade, term)];
    for (let i = pool.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return pool.slice(0, Math.max(0, count));
  },
